import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "Sphere",
        Title: data.title || "Sphere Document",
        Creator: "Sphere",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => {
      chunks.push(chunk);
    });

    doc.on("end", () => {
      resolve(Buffer.concat(chunks));
    });

    doc.on("error", reject);

    // Title
    doc
      .fillColor("#111827")
      .fontSize(28)
      .font("Helvetica-Bold")
      .text(data.title || "Untitled Document", {
        align: "center",
      });

    // Subtitle
    if (data.subtitle) {
      doc
        .moveDown(0.5)
        .fillColor("#6B7280")
        .fontSize(12)
        .font("Helvetica")
        .text(data.subtitle, {
          align: "center",
        });
    }

    doc.moveDown(2);

    // Sections
    const sections = Array.isArray(data.sections)
      ? data.sections
      : [];

    sections.forEach((section) => {
      if (!section?.heading) {
        return;
      }

      doc
        .fillColor("#111827")
        .fontSize(18)
        .font("Helvetica-Bold")
        .text(section.heading);

      doc.moveDown(0.5);

      const points = Array.isArray(section.points)
        ? section.points
        : [];

      points.forEach((point) => {
        if (!point) {
          return;
        }

        doc
          .fillColor("#374151")
          .fontSize(12)
          .font("Helvetica")
          .text(`• ${point}`, {
            lineGap: 5,
          });
      });

      doc.moveDown();
    });

    // Footer
    doc
      .moveDown()
      .fillColor("#9CA3AF")
      .fontSize(10)
      .font("Helvetica")
      .text("Generated by Sphere", {
        align: "center",
      });

    doc.end();
  });
};